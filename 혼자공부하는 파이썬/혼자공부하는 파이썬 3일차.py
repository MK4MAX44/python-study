## 문자열 연결 연산자(+)
# 문자열 + 문자열
print("문자열" + "문자열")

## 문자열 반복 연산자(*)
# 숫자 * 문자열 또는 문자열 * 숫자
print("문자열" * 3)
print(3 * "문자열")

## 문자 선택 연산자 - 인덱싱([ ])
# 문자열[숫자] ➢ 특정 위치의 문자 하나를 선택
# 인덱스는 0부터 시작, 음수 인덱스는 뒤에서부터 (-1: 맨 마지막 글자)
print("adsdf"[-1])

## 문자열 자르기 - 슬라이싱([:])
# 문자열[숫자a:숫자b] ➢ 숫자a번째부터 숫자b번째 "직전"까지 선택 (숫자b는 포함 안 함)
# 앞/뒤 숫자를 생략하면 "처음부터" / "끝까지"라는 뜻
# 안녕하세요[0:3] = 안녕하 (0,1,2번째 → 3번째는 미포함)
# 안녕하세요[:3]  = 안녕하 (처음부터 3번째 직전까지, 위와 동일)
# 안녕하세요[3:]  = 세요   (3번째부터 끝까지)

## 인덱싱 / 슬라이싱 연습 (95쪽 문제, "안녕하세요"로 연습)
# 인덱스(양수):  0=안  1=녕  2=하  3=세  4=요
# 인덱스(음수): -5=안 -4=녕 -3=하 -2=세 -1=요
word = "안녕하세요"
print(word[0])    # 안
print(word[2])    # 하
print(word[3])    # 세
print(word[-1])   # 요 (맨 마지막 글자)

print(word[0:1])  # 안
print(word[0:2])  # 안녕
print(word[2:3])  # 하
print(word[2:])   # 하세요 (2번째부터 끝까지)
print(word[:])    # 안녕하세요 (전체, 콜론 앞뒤 생략)

## 슬라이싱에 증가값(스텝) 추가하기
# 문자열[숫자a:숫자b:스텝] ➢ 스텝만큼 건너뛰며 자르기
numbers = "0123456789"
print(numbers[::1])  # 0123456789 (1스텝 = 전부 다)
print(numbers[::2])  # 02468
print(numbers[::3])  # 0369
print(numbers[::4])  # 048
print(numbers[::5])  # 05

print(word[1:4:2])   # 녕세 (1번째, 3번째만 선택)
print(word[::2])     # 안하요 (전체를 2칸씩 건너뛰며 선택)

## 용어 정리
# 인덱스(index): 문자열 안에서 위치를 나타내는 숫자
# 문자열[인덱스] 처럼 인덱스를 하나만 써서 문자 하나를 뽑는 것 ➢ 인덱싱(indexing)
# 문자열[인덱스:인덱스] / 문자열[인덱스:인덱스:스텝] 처럼 범위로 잘라내는 것 ➢ 슬라이싱(slicing)
