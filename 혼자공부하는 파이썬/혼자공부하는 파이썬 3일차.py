# 기본 자료형


## 문자형 ➢ str(string)

print(type("안녕하세요"))
print(type("Hell World"))

# 숫자
# 정수 ➢ int(Integer)
# 실수 = 부동소수점 ➢ float(Floating point)
print(type(52.333))

# 불 : bool(Boolean)
print(type(True)) # 참
print(type(False)) # 거짓

# 복합자료형
## 기본 자료형이 복합적으로 섞여 있는 것

